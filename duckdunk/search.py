def set_tuple_params(params, key, value):
    for i in range(len(params)):
        item = params[i]
        if item[0] == key:
            params[i] = (key, value)

def resolve_duckduckgo(query: str) -> str:
    """Queries DuckDuckGo and returns the raw HTML"""
    res = requests.post('https://duckduckgo.com/', data={'q': query}, headers=headers.DEFAULT)
    return res.text

def web_search(
        query, 
        delay: int = 1,
        time_frame: str = "Any",
        locale: str | None = None, 
        country: str | None = None, 
        bing_market: str | None = None,
        auto_configure_locale: bool = True,
        strict_search: bool = False,
        safe_search: bool = True,
        ):
    """
    Searches for websites on DuckDuckGo given a query.

    This function does not work with spaces in the query.
    Every other query (except probably special characters)
    seems to work fine.
    It is NOT a mismatch between VQD and the query, I found
    out that gives an error rather than an empty output.
    
    Args:
        query: The search query. Searching "cat facts" yields websites about cats
        delay: An optional delay in seconds before the function runs
        time_frame: Limits the time frame in which results became available.
            Allowed values are: "Any", "Daily", "Weekly", "Monthly", "Yearly"
            Optionally you may also enter: "", "a", "d", "w", "m", "y"
            Only the first letter is checked
        locale: Configures the locale setting of DuckDuckGo
            Make sure to enter a valid ISO 639 language code preceded
            by a valid ISO 3166 code, for example: us-en
        country: The country code, another part of the locale settings.
            Make sure to enter a valid ISO 3166 code, for example: US
        bing_market: The locale for Bing, presumably for marketing, judging by the name.
            Must be the reverse of locale: en-US.
        auto_configure_locale: If set to True, `country` and `bing_market` will
            be set automatically based on `locale`.
        strict_search: Enables strict searching. This does nothing if safe search is disabled.
            This is untested.
        safe_search: When enabled, unsafe content is hidden. This is the default behavior.
            Disabling this setting is untested.
    """
    params = _get_djs_params(query)
    
    # Configure the time frame
    allowed_timeframes = ('a', 'd', 'w', 'm', 'y')
    if len(time_frame) > 0:
        c = time_frame[0].lower()
        if c in allowed_timeframes:
            if c != 'a':
                params['df'] = c
        else:
            raise ValueError(f"Timeframe {time_frame} not recognized. The first character must be one of: {allowed_timeframes}")

    # Configure locale parameters
    if locale != None:
        params['l'] = locale.lower()
        # The next two locale parameters can usually be assumed from the locale
        if auto_configure_locale:
            splits = locale.split('-')
            params['ct'] = splits[0].upper()
            params['bing_market'] = splits[1] + '-' + splits[0].upper()

    if country != None:
        params['ct'] = country.upper()
    if bing_market != None:
        params['bing_market'] = bing_market

    # Enable strict searching
    if safe_search:
        if strict_search:
            # This is the only variable that
            # seems to change when strict
            # searching is enabled.
            params['p'] = '1'
    else:
        # This is the only variable that seems
        # to change when safe search is disabled.
        params['ex'] = '-2'

    # Delay just because
    time.sleep(delay)

    tparams = [(key, value) for key, value in params.items()]

    # Make the request
    res = requests.get(
            'https://duckduckgo.com/d.js', 
            headers=headers.DUCKDUCKGO_WEB_SEARCH, 
            params=tparams
            )
    # Extract text from the result
    result_text = res.text

    # A summary answer is provided here
    # instant_answer = util.extract_json(full, r'DDG\.deep\.deepPayload = ', r'\);DDG.duckbar')

    # The website results are retreived and converted to Python objects
    results = util.extract_json(result_text, r'DDG\.pageLayout\.load\(\'d\',', r'\);')
    out = []
    for item in results:
        try:
            out.append(DuckDetailedLink(
                item['a'] if 'a' in item.keys() else '', # Not all results will have previews
                item['ae'],
                '', # item['b'],
                item['c'],
                item['d'],
                item['da'].split(','),
                item['h'],
                item['i'],
                0, # int(item['m']),
                0, # int(item['o']),
                0, # int(item['p']),
                0, # int(item['s']),
                item['t'],
                item['u']
            ))
        except:
            logging.debug("Discarded an invalid link")

    # The results are returned
    return out

def html_web_search(query, delay: int = 1) -> list[DuckHTMLLink]:
    """
    Performs a web search using DuckDuckGo and returns the result list.

    Each list item contains a `url`, `title`, and `snippet`.

    Args:
        query: The search query. A search of "cat facts" will return 
            web pages with cat facts.
        delay: A fixed delay before the request is made to prevent getting blocked.
            The search tests were actually failing without this delay.

    Returns:
        A list of links with titles and descriptions
    """
    # DuckDuckGo refuses large numbers of requests, so this delay tries to prevent that
    time.sleep(delay)

    # The search is made directly with a GET request
    url = f'http://duckduckgo.com/html/?q={query}'
    listing = download_soup(url, headers.DEFAULT)

    containers = listing.find_all('div', {'class': re.compile('links_main*')})
    if len(containers) == 0:
        raise PageRefusalException("Client was detected as a bot. Either too many requests were sent, the search failed, or invalid headers were sent.")

    results = []
    # Every result in the list is in a `div` of class "links_main"
    # So, a "links_main" class is a container for the title, url, icon, and snippet.
    for links in containers:
        # The title has the class "result__a" for some reason
        title_obj = links.find('a', {'class': re.compile('result__a')})
        assert title_obj != None
        # Both the text and URL are taken from the title link
        link_title = title_obj.text
        link_url = str(title_obj.get('href'))
        assert type(link_url) == str
        # The snippet makes more sense
        snippet_obj = links.find('a', {'class': re.compile('result__snippet')})
        link_snippet = ''
        # In case the snippet is missing (which may never be the case),
        # the actual snippet is only assigned if the snippet was present.
        if snippet_obj != None:
            link_snippet = snippet_obj.text
        # The three variables are put into a container class
        results.append(DuckHTMLLink(link_url, link_title, link_snippet))
    return results

def _validate_flag_enum(flag, valid: tuple) -> str:
    flag = str(flag).title()
    if flag != 'any':
        if type(flag) != str:
            raise TypeError(f"Argument has incorrect type \"{type(flag)}\", should be str.")
        if flag not in valid:
            raise ValueError(f"Flag \"{flag}\" is not valid. Should be one of: {valid}")
    return flag

def _try_add_string_flag(key, flag, valid: tuple):
    flag = _validate_flag_enum(flag, valid)
    if flag != 'Any':
        return f',{key}:{flag}'
    return ''

def image_search(query, hide_ai_images: bool = True, time_range: str = 'Any', size: str = 'Any', layout: str = 'Any', locale='us-en', delay: int = 1) -> list[DuckImage]:
    """
    Search the DuckDuckGo image database.

    This sends back a variable number of images. It
    can be less than twenty, or it can be over thirty.
    Keep in mind, the images must be manually downloaded
    afterward. For example:

    ```
    results = image_search('cat')
    img = results[0].download()
    ``` 

    Args:
        query: The search query. "Cat" will yield cat images.
        hide_ai_images: Whether or not to try hiding some AI images.
        time_range: 
            Time range of allowed results in the past day, month, or week.
            Allowed values are 'Any', 'Day', 'Week', 'Month'.
        size: 
            The estimated size of the images returned.
            Allowed values are 'Any', 'Small', 'Medium', 'Large', 'Wallpaper'.
        layout:
            The shape of the image results
            Allowed values are 'Any', 'Square', 'Tall', 'Wide'.
        locale: Changes the results to be catered toward a different region.
            Make sure to enter a valid ISO 639 language code preceded
            by a valid ISO 3166 code.
             
            Not all languages/regions are supported by search engines.
            This field is untested and may do nothing right now.
        delay: A fixed delay before the request is made to prevent getting blocked.
    """
    # Obtain search variables for unofficial API calls 
    raw_data = resolve_duckduckgo(query)
    # tjs = _get_all_tjs(raw_data)
    js = _get_all_javascript_var(raw_data)
    
    # DuckDuckGo refuses large numbers of requests, this manages them.
    time.sleep(delay)

    # Flags are assembled directly in a string
    flags = f'hide_ai_images:{int(hide_ai_images)}'

    # Add any valid flags that aren't "Any"
    flags += _try_add_string_flag('time', time_range, ('Any', 'Day', 'Week', 'Month'))
    flags += _try_add_string_flag('size', size, ('Any', 'Small', 'Medium', 'Large', 'Wallpaper'))
    flags += _try_add_string_flag('layout', layout, ('Any', 'Square', 'Tall', 'Wide'))

    # Parameters sent with the POST request
    params = (
        ('o', 'json'), # o : probably the desired response format?
        ('q', query), # q : search query
        ('l', locale), # l : language/region
        ('p', '1'),
        ('vqd', js['vqd']), # The search hash
        ('ct', js['ct']), # country
        # ('dp', tjs['dp']),
        ('f', flags), # f : filters (key:value,)
        ('bpia', '1'),
        ('a', 'h_'),
        # ('v7exp', 'a'), 
    )

    # Attempts downloading the data
    res = requests.get(
        'https://duckduckgo.com/i.js', 
        headers=headers.DUCKDUCKGO_IMAGE_SEARCH, 
        params=params
        )
    data = json.loads(res.text);

    # Reassembles the dict list as an array of DuckImage objects
    items = []
    for item in data['results']:
        items.append(
            DuckImage(
                item['encoding_format'], 
                int(item['width']), 
                int(item['height']), 
                item['thumbnail'], 
                item['url'], 
                item['title'], 
                item['image']
                )
            )
    return items
