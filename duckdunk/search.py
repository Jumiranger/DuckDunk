class DuckImage:
    def __init__(self, encoding: str, width: int, height: int, thumbnail: str, url: str, title: str, image: str):
        self.encoding = encoding
        """The image format."""
        self.width = width
        self.height = height
        self.thumbnail = thumbnail
        """The thumbnail URL generated by Bing. Provides a smaller version 
        of the original image and is recommended in all cases."""
        self.url = url
        """This is NOT the image URL, but the URL of the site 
        the image came from, e.g. a news source. For the image,
        use `thumbnail` or `image` for an image URL."""
        self.title = title
        """This is the text underneath the image when previewing."""
        self.image = image
        """The original image URL. Not recommended as this can be 
        a very large download. Moreover, this link can fail if the
        incorrect headers are provided. Unless you REALLY need to
        use the original image, use `thumbnail` instead."""

    def __repr__(self) -> str:
        return f"DuckImage{self.__dict__}"

    def download(self, original: bool = False) -> Image.Image:
        """
        Downloads the image as a PIL image.

        Either downloads the generated thumbnail from Bing,
        or the original. Headers are not sent, and many sites
        will deny access to their URLs. You'll have to write
        your own image download method for properly obtaining
        the original. Otherwise, downloading the thumbnail
        rarely fails.
        
        Args:
            original: Whether or not to download the original image. 
                False is recommended.
        
        Returns:
            An image from either chosen URL.
        """
        if original:
            return download_image(self.image)
        else:
            return download_image(self.thumbnail)

class DuckHTMLLink:
    """Container for link information."""
    def __init__(self, url: str, title: str, snippet: str = ''):
        self.url = url
        self.title = title
        self.snippet = snippet
        """A preview of the page"""

    def soup(self, headers=None) -> BeautifulSoup:
        """Downloads and parses the HTML from the external link."""
        return download_soup(self.url, headers)

    def text(self, headers=None) -> str:
        """Downloads text from the external link."""
        return self.soup(headers).text

class DuckDetailedLink:
    """Container for detailed link information."""
    def __init__(
            self, 
            snippet: str, # Called 'a'
            ae: str, # Seemingly always null
            formatted_heading: str, # Website title \t website URL
            full_link: str, # Called 'c', includes the "https://"" prefix
            partial_link: str, # Called 'd', does not include the "https://"" prefix
            tags: list[str], # Called 'da', used on some sites, videos include many
            h: int, # Always 0
            home: str, # Called 'i', the normalized web link, e.g. "www.britannica.com"
            m: int, # Always 0
            o: int, # Always 0
            p: int, # Always 0
            s: int, # Always "bingv7aa"
            title: str, # Called 't', this is the title of the result, e.g. "77 Cat Facts That Will Surprise Even Cat Lovers"
            url: str, # Called 'u'. Seems identical to 'c' (full link)
            ):
        """
        Initialize data arguments

        Args:
            snippet: Called 'a'
            ae: Seemingly always null
            formatted_heading: Called 'b'. Website title combined with the URL
            full_link: Called 'c'. Includes the "https://"" prefix
            partial_link: Called 'd'. Does not include the "https://"" prefix
            tags: Called 'da'. used on some sites, videos include many
            h: Always 0
            home: Called 'i', the normalized web link, e.g. "www.britannica.com"
            m: Always 0
            o: Always 0
            p: Always 0
            s: Always "bingv7aa"
            title: Called 't', this is the title of the result, e.g. "77 Cat Facts That Will Surprise Even Cat Lovers"
            url: Called 'u'. Seems identical to 'c' (full link)
        """
        self.snippet = snippet
        self.ae = ae
        self.formatted_heading = formatted_heading
        self.full_link = full_link
        self.partial_link = partial_link
        self.tags = tags
        self.h = h
        self.home = home
        self.m = m
        self.o = o
        self.p = p
        self.s = s
        self.title = title
        self.url = url

    def soup(self, headers=None) -> BeautifulSoup:
        """Downloads and parses the HTML from the external link."""
        return download_soup(self.url, headers)
    
    def text(self, headers=None) -> str:
        """Downloads text from the external link."""
        return self.soup(headers).text

class PageRefusalException(Exception):
    """Exception for when the client is detected as a bot."""
    def __init__(self, text: str):
        super().__init__(text)

def _get_all_tjs(text) -> dict[str, str]:
    """Get all variables sent to DuckDuckGo's t.js"""
    return util.extract_dict(text, r'/t\.js\?', r'></script>', '&', '=')

def _get_all_javascript_var(text) -> dict[str, str]:
    """Get unlabeled variables from DuckDuckGo"""
    return util.extract_dict(
        text, r'<script type="text/javascript">var ', r';function', ',', '=')

